    private void editButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editButtonActionPerformed
        try {
//            System.out.println(discountTable.getSelectedRow());
            if(discountTable.getSelectedRow()!=-1){
                
                System.out.println("dat : "+(new SimpleDateFormat("dd/MM/yyyy").parse(discountTable.getValueAt(discountTable.getSelectedRow(), 1).toString())));
                edate.setDate(((new SimpleDateFormat("dd/MM/yyyy").parse(discountTable.getValueAt(discountTable.getSelectedRow(), 1).toString()))));
//                System.out.println(discountTable.getValueAt(discountTable.getSelectedRow(), 1));
                amount.setText(commonMethods.rupee(discountTable.getValueAt(discountTable.getSelectedRow(), 3).toString()));
                model = ((Discount_Damage_PreBalanceTableModel)this.discountTable.getModel()).getModel(discountTable.getSelectedRow());
                if(model.getMsg().equalsIgnoreCase("discount")){
                upReason.setSelectedIndex(1);
                } else if(model.getMsg().equalsIgnoreCase("damage")){
                 upReason.setSelectedIndex(2);   
                
                } else {
                 upReason.setSelectedIndex(3);   
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_editButtonActionPerformed

