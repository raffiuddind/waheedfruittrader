    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            List<StatementModel> statementModel = new ArrayList<>();
            long total = 0;
            for(int i=0; i < discountTable.getModel().getRowCount(); i++){
              DiscountModel dm = ((Discount_Damage_PreBalanceTableModel)this.discountTable.getModel()).getModel(i);
             StatementModel model = new StatementModel(i+1, dm.getDt(), dm.getName(), null, 
                     commonMethods.rupee(String.valueOf(dm.getAmount())), dm.getMsg());
             statementModel.add(model);
             total = total + dm.getAmount();
             
            }
            if(statementModel.size()>0){
                  JRBeanCollectionDataSource beanCollectionDataSource = new JRBeanCollectionDataSource(statementModel);
                  Map m = new HashMap();
                  m.put("totalDiscount", commonMethods.rupee(String.valueOf(total)));
                  m.put("pl", "");
                try {
                    JasperDesign design = JRXmlLoader.load("Business_Report\\discountReport.jrxml");
                    JasperReport jasperReport = JasperCompileManager.compileReport(design);
                    JasperPrint jasperPrint = JasperFillManager.fillReport(jasperReport, m, beanCollectionDataSource);
                    JasperViewer jasperViewer = new JasperViewer(jasperPrint, false);
                    jasperViewer.setVisible(true);
                } catch (Exception e) {
                    e.printStackTrace();
                }
                } else {
                    JOptionPane.showMessageDialog(null, "No data");
                }
            
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

